/**
 * Reads the Alined DS tokens (design/tokens.json, W3C design tokens format: light values in
 * `$value`, dark values in `$extensions["co.alinedlabs.modes"].dark`) and turns them into
 * src/styles/tokens.css, src/styles/theme.css and design/contrast-report.md. Pure functions only:
 * design/build-tokens.mjs writes the files, src/styles/tokens.test.ts checks them, and the app
 * reads resolved colours from here (the manifest and the theme colour).
 */

export type Theme = "light" | "dark";
export const THEMES: readonly Theme[] = ["light", "dark"];

export type Token = {
  $type?: string;
  $value: unknown;
  $description?: string;
  $extensions?: Record<string, { dark?: unknown } | undefined>;
};
type Group = Record<string, Token>;
export type Tokens = {
  primitive: Record<string, Group>;
  color: Group;
  font: Group;
  type: Group;
  space: Group;
  radius: Group;
  shadow: Group;
  layout: Group;
  zIndex: Group;
  duration: Group;
  easing: Group;
};
/** A text or mark colour checked on each of its grounds, in both themes. */
export type Pair = { fg: string; grounds: string[]; min: number; kind: string };
/** pairs.json: the contrast pairs, and the colours that must stay apart. */
export type Checks = { pairs: Pair[]; distinct: { min: number; groups: string[][] } };
type TypeStyle = {
  fontSize: string;
  lineHeight: string;
  fontWeight: number;
  letterSpacing: string;
};
type Rgb = [number, number, number];
type Matrix = [Rgb, Rgb, Rgb];
export type Vision = "normal" | "protanopia" | "deuteranopia" | "tritanopia";

const MODES = "co.alinedlabs.modes";
const HEADER =
  "Alined DS, Plumbline theme. Generated by design/build-tokens.mjs from design/tokens.json: " +
  "edit the JSON and run the script, never this file.";

/** A token's value in one theme: the dark mode falls back to the light value. */
function themed(token: Token, theme: Theme): unknown {
  const dark = token.$extensions?.[MODES]?.dark;
  return theme === "dark" && dark !== undefined ? dark : token.$value;
}

function lookup(tokens: Tokens, path: string): Token {
  let node: unknown = tokens;
  for (const key of path.split(".")) {
    if (typeof node !== "object" || node === null || !(key in node)) {
      throw new Error(`unknown token {${path}}`);
    }
    node = (node as Record<string, unknown>)[key];
  }
  if (typeof node !== "object" || node === null || !("$value" in node)) {
    throw new Error(`{${path}} is a group, not a token`);
  }
  return node as Token;
}

/** Follows {references} until a literal value, in the given theme. Numbers become strings. */
export function resolve(tokens: Tokens, value: unknown, theme: Theme, depth = 0): string {
  if (typeof value === "number") return String(value);
  if (typeof value !== "string") throw new Error(`expected a string, got ${JSON.stringify(value)}`);
  const ref = /^\{([^}]+)\}$/.exec(value)?.[1];
  if (ref === undefined) return value;
  if (depth > 8) throw new Error(`reference loop at ${value}`);
  return resolve(tokens, themed(lookup(tokens, ref), theme), theme, depth + 1);
}

/** One semantic colour in one theme, resolved to hex. */
export function colorOf(tokens: Tokens, name: string, theme: Theme): string {
  const token = tokens.color[name];
  if (token === undefined) throw new Error(`unknown colour ${name}`);
  return resolve(tokens, themed(token, theme), theme);
}

/** Every semantic colour, resolved to hex, per theme. */
export function resolveColors(tokens: Tokens): Record<Theme, Record<string, string>> {
  const out: Record<Theme, Record<string, string>> = { light: {}, dark: {} };
  for (const theme of THEMES) {
    for (const [name, token] of Object.entries(tokens.color)) {
      out[theme][name] = resolve(tokens, themed(token, theme), theme);
    }
  }
  return out;
}

// ---- colour arithmetic ------------------------------------------------------------------------

function rgba(hex: string): { rgb: Rgb; alpha: number } {
  const match = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})?$/i.exec(hex);
  if (!match) throw new Error(`not a hex colour: ${hex}`);
  const [, r = "", g = "", b = "", a = "ff"] = match;
  return { rgb: [parseInt(r, 16), parseInt(g, 16), parseInt(b, 16)], alpha: parseInt(a, 16) / 255 };
}

/** Rounds half to even, as the design pipeline does, so both produce the same 8-bit colours. */
function roundEven(x: number): number {
  const floor = Math.floor(x);
  const diff = x - floor;
  if (diff > 0.5) return floor + 1;
  if (diff < 0.5) return floor;
  return floor % 2 === 0 ? floor : floor + 1;
}

/** A translucent colour flattened over its ground, rounded to 8 bits per channel. */
function flatten(color: string, ground: Rgb): Rgb {
  const { rgb, alpha } = rgba(color);
  if (alpha === 1) return rgb;
  const mix = (i: 0 | 1 | 2) => roundEven(alpha * rgb[i] + (1 - alpha) * ground[i]);
  return [mix(0), mix(1), mix(2)];
}

const toLinear = (c: number) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const toGamma = (c: number) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
const linear = (rgb: Rgb): Rgb => [
  toLinear(rgb[0] / 255),
  toLinear(rgb[1] / 255),
  toLinear(rgb[2] / 255),
];

function luminance(rgb: Rgb): number {
  const [r, g, b] = linear(rgb);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** WCAG 2.2 contrast of a colour on a ground; translucent grounds sit on the page canvas. */
export function contrast(color: string, ground: string, canvas: string): number {
  const base = flatten(ground, rgba(canvas).rgb);
  const [a, b] = [luminance(flatten(color, base)), luminance(base)];
  return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
}

/** Machado, Oliveira and Fernandes (2009), full severity, applied in linear RGB. */
const DEFICIENCY: Record<Exclude<Vision, "normal">, Matrix> = {
  protanopia: [
    [0.152286, 1.052583, -0.204868],
    [0.114503, 0.786281, 0.099216],
    [-0.003882, -0.048116, 1.051998],
  ],
  deuteranopia: [
    [0.367322, 0.860646, -0.227968],
    [0.280085, 0.672501, 0.047413],
    [-0.01182, 0.04294, 0.968881],
  ],
  tritanopia: [
    [1.255528, -0.076749, -0.178779],
    [-0.078411, 0.930809, 0.147602],
    [0.004733, 0.691367, 0.3039],
  ],
};

/** The colour as a reader with the given colour vision sees it, rounded to 8 bits. */
export function simulate(rgb: Rgb, vision: Vision): Rgb {
  if (vision === "normal") return rgb;
  const m = DEFICIENCY[vision];
  const lin = linear(rgb);
  const row = (r: Rgb) => r[0] * lin[0] + r[1] * lin[1] + r[2] * lin[2];
  const out = (r: Rgb) =>
    Math.max(0, Math.min(255, roundEven(toGamma(Math.min(1, Math.max(0, row(r)))) * 255)));
  return [out(m[0]), out(m[1]), out(m[2])];
}

/** CIE L*a*b* under D65. */
function lab(rgb: Rgb): Rgb {
  const [r, g, b] = linear(rgb);
  const x = 0.4124 * r + 0.3576 * g + 0.1805 * b;
  const y = 0.2126 * r + 0.7152 * g + 0.0722 * b;
  const z = 0.0193 * r + 0.1192 * g + 0.9505 * b;
  const f = (t: number) => (t > 216 / 24389 ? Math.cbrt(t) : ((24389 / 27) * t + 16) / 116);
  const [fx, fy, fz] = [f(x / 0.95047), f(y), f(z / 1.08883)];
  return [116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)];
}

const rad = (deg: number) => (deg * Math.PI) / 180;
const deg = (r: number) => ((((r * 180) / Math.PI) % 360) + 360) % 360;

/** CIEDE2000 colour difference (Sharma, Wu and Dalal, 2005). */
export function deltaE2000(one: Rgb, two: Rgb): number {
  const [L1, a1, b1] = lab(one);
  const [L2, a2, b2] = lab(two);
  const Cb = (Math.hypot(a1, b1) + Math.hypot(a2, b2)) / 2;
  const G = 0.5 * (1 - Math.sqrt(Cb ** 7 / (Cb ** 7 + 25 ** 7)));
  const [a1p, a2p] = [(1 + G) * a1, (1 + G) * a2];
  const [C1p, C2p] = [Math.hypot(a1p, b1), Math.hypot(a2p, b2)];
  const [h1p, h2p] = [deg(Math.atan2(b1, a1p)), deg(Math.atan2(b2, a2p))];
  const [dLp, dCp] = [L2 - L1, C2p - C1p];
  let dhp = 0;
  if (C1p * C2p !== 0) {
    dhp = h2p - h1p;
    if (dhp > 180) dhp -= 360;
    else if (dhp < -180) dhp += 360;
  }
  const dHp = 2 * Math.sqrt(C1p * C2p) * Math.sin(rad(dhp / 2));
  const [Lbp, Cbp] = [(L1 + L2) / 2, (C1p + C2p) / 2];
  let hbp = h1p + h2p;
  if (C1p * C2p !== 0) {
    if (Math.abs(h1p - h2p) <= 180) hbp = (h1p + h2p) / 2;
    else if (h1p + h2p < 360) hbp = (h1p + h2p + 360) / 2;
    else hbp = (h1p + h2p - 360) / 2;
  }
  const T =
    1 -
    0.17 * Math.cos(rad(hbp - 30)) +
    0.24 * Math.cos(rad(2 * hbp)) +
    0.32 * Math.cos(rad(3 * hbp + 6)) -
    0.2 * Math.cos(rad(4 * hbp - 63));
  const dTheta = 30 * Math.exp(-(((hbp - 275) / 25) ** 2));
  const Rc = 2 * Math.sqrt(Cbp ** 7 / (Cbp ** 7 + 25 ** 7));
  const Sl = 1 + (0.015 * (Lbp - 50) ** 2) / Math.sqrt(20 + (Lbp - 50) ** 2);
  const [Sc, Sh] = [1 + 0.045 * Cbp, 1 + 0.015 * Cbp * T];
  const Rt = -Math.sin(rad(2 * dTheta)) * Rc;
  return Math.sqrt(
    (dLp / Sl) ** 2 + (dCp / Sc) ** 2 + (dHp / Sh) ** 2 + Rt * (dCp / Sc) * (dHp / Sh),
  );
}

export const VISIONS: readonly Vision[] = ["normal", "protanopia", "deuteranopia", "tritanopia"];

/** CIEDE2000 between two opaque colours, with normal vision and each simulated deficiency. */
export function distances(one: string, two: string): Record<Vision, number> {
  const [a, b] = [rgba(one).rgb, rgba(two).rgb];
  const out = { normal: 0, protanopia: 0, deuteranopia: 0, tritanopia: 0 };
  for (const vision of VISIONS) out[vision] = deltaE2000(simulate(a, vision), simulate(b, vision));
  return out;
}

/** Every unordered pair within each group, in order. */
export function pairsOf(groups: string[][]): [string, string][] {
  return groups.flatMap((group) =>
    group.flatMap((one, i) => group.slice(i + 1).map((two): [string, string] => [one, two])),
  );
}

// ---- generated files --------------------------------------------------------------------------

function typeStyle(name: string, token: Token): TypeStyle {
  const v = token.$value as Partial<TypeStyle> | null;
  if (
    typeof v?.fontSize !== "string" ||
    typeof v.lineHeight !== "string" ||
    typeof v.fontWeight !== "number" ||
    typeof v.letterSpacing !== "string"
  ) {
    throw new Error(`type.${name} needs fontSize, lineHeight, fontWeight and letterSpacing`);
  }
  return v as TypeStyle;
}

const rem = (px: string) => `${parseFloat(px) / 16}rem`;

/** The CSS custom properties, light and dark, with the reduced-motion override. */
export function tokensCss(tokens: Tokens): string {
  const colors = resolveColors(tokens);
  const themedBlock = (theme: Theme, indent: string) => [
    ...Object.keys(tokens.color).map((n) => `${indent}--pl-color-${n}: ${colors[theme][n]};`),
    ...Object.entries(tokens.shadow).map(
      ([n, token]) => `${indent}--pl-${n}: ${resolve(tokens, themed(token, theme), theme)};`,
    ),
  ];
  const fonts = Object.entries(tokens.font).map(([key, token]) => {
    const stack = resolve(tokens, token.$value, "light");
    const comma = stack.indexOf(",");
    const [first, rest] = comma === -1 ? [stack, ""] : [stack.slice(0, comma), stack.slice(comma)];
    return `  --pl-font-${key}: var(--pl-face-${key}, ${first.trim()})${rest};`;
  });
  const type = Object.entries(tokens.type).flatMap(([n, token]) => {
    const s = typeStyle(n, token);
    return [
      `  --pl-text-${n}: ${rem(s.fontSize)};`,
      `  --pl-text-${n}--line-height: ${rem(s.lineHeight)};`,
      `  --pl-text-${n}--letter-spacing: ${s.letterSpacing};`,
      `  --pl-text-${n}--font-weight: ${s.fontWeight};`,
    ];
  });
  const plain = (group: Group) =>
    Object.entries(group).map(
      ([n, token]) => `  --pl-${n}: ${resolve(tokens, token.$value, "light")};`,
    );
  const easing = Object.entries(tokens.easing).map(([n, token]) => {
    if (!Array.isArray(token.$value)) throw new Error(`easing.${n} must be four numbers`);
    return `  --pl-${n}: cubic-bezier(${token.$value.join(", ")});`;
  });
  return [
    `/* ${HEADER} */`,
    "",
    ":root {",
    ...themedBlock("light", "  "),
    "",
    ...fonts,
    "",
    ...type,
    "",
    ...plain(tokens.radius),
    ...plain(tokens.layout),
    ...plain(tokens.zIndex),
    ...plain(tokens.duration),
    ...easing,
    "",
    "  color-scheme: light;",
    "}",
    "",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    ...themedBlock("dark", "    "),
    "    color-scheme: dark;",
    "  }",
    "}",
    "",
    ':root[data-theme="dark"] {',
    ...themedBlock("dark", "  "),
    "  color-scheme: dark;",
    "}",
    "",
    "@media (prefers-reduced-motion: reduce) {",
    "  :root {",
    ...Object.keys(tokens.duration).map((n) => `    --pl-${n}: 0ms;`),
    "  }",
    "}",
    "",
  ].join("\n");
}

/** The Tailwind 4 theme. Colours, type sizes, radii, shadows and easings are reset to the
 * system's, so a utility outside it (text-sm, bg-white, shadow-md, ease-in) does not exist. */
export function themeCss(tokens: Tokens): string {
  const alias = (group: Group) => Object.keys(group).map((n) => `  --${n}: var(--pl-${n});`);
  return [
    `/* ${HEADER} */`,
    "/* Imported by app/globals.css. Utilities such as bg-surface, text-fg-muted, text-body,",
    "   rounded-md and shadow-2 read the variables in tokens.css. */",
    "@theme inline {",
    "  --color-*: initial;",
    ...Object.keys(tokens.color).map((n) => `  --color-${n}: var(--pl-color-${n});`),
    "",
    ...Object.keys(tokens.font).map((k) => `  --font-${k}: var(--pl-font-${k});`),
    "",
    "  --text-*: initial;",
    ...Object.keys(tokens.type).flatMap((n) => [
      `  --text-${n}: var(--pl-text-${n});`,
      `  --text-${n}--line-height: var(--pl-text-${n}--line-height);`,
      `  --text-${n}--letter-spacing: var(--pl-text-${n}--letter-spacing);`,
      `  --text-${n}--font-weight: var(--pl-text-${n}--font-weight);`,
    ]),
    "",
    "  --radius-*: initial;",
    ...alias(tokens.radius),
    "",
    "  --shadow-*: initial;",
    "  --inset-shadow-*: initial;",
    "  --drop-shadow-*: initial;",
    "  --text-shadow-*: initial;",
    ...alias(tokens.shadow),
    "",
    "  --ease-*: initial;",
    ...alias(tokens.easing),
    "  --default-transition-duration: var(--pl-duration-fast);",
    "  --default-transition-timing-function: var(--pl-ease-standard);",
    "",
    "  --container-content: var(--pl-content-max);",
    "  --container-panel: var(--pl-panel-width);",
    "}",
    "",
  ].join("\n");
}

/** Every pair's contrast in both themes, then the distances between colours that must differ. */
export function contrastReport(tokens: Tokens, checks: Checks): string {
  const colors = resolveColors(tokens);
  const rows: string[] = [];
  let failures = 0;
  for (const pair of checks.pairs) {
    for (const theme of THEMES) {
      const c = colors[theme];
      for (const ground of pair.grounds) {
        const ratio = contrast(c[pair.fg] ?? "", c[ground] ?? "", c.bg ?? "");
        const ok = ratio >= pair.min;
        if (!ok) failures += 1;
        rows.push(
          `| ${theme} | \`${pair.fg}\` ${c[pair.fg]} | \`${ground}\` ${c[ground]} | ` +
            `${ratio.toFixed(2)} | ${pair.min} | ${ok ? "pass" : "FAIL"} |`,
        );
      }
    }
  }
  const apart: string[] = [];
  for (const [one, two] of pairsOf(checks.distinct.groups)) {
    for (const theme of THEMES) {
      const d = distances(colors[theme][one] ?? "", colors[theme][two] ?? "");
      apart.push(
        `| ${theme} | \`${one}\` / \`${two}\` | ` +
          VISIONS.map((vision) => d[vision].toFixed(1)).join(" | ") +
          " |",
      );
    }
  }
  return [
    "# Contrast report",
    "",
    "Generated by `design/build-tokens.mjs` from `tokens.json` and `pairs.json`;",
    "`src/styles/tokens.test.ts` fails when this file is out of date.",
    "",
    "Every text colour on every ground its usage note names, in both themes. WCAG 2.2 asks 4.5:1 for",
    "text and 3:1 for control edges, focus rings, icons and chart marks.",
    "",
    "| Theme | Foreground | Ground | Ratio | Minimum | Result |",
    "| --- | --- | --- | ---: | ---: | --- |",
    ...rows,
    "",
    `**${failures} ${failures === 1 ? "failure" : "failures"}.**`,
    "",
    "## Colours that must be told apart",
    "",
    "CIEDE2000 distance between each pair, with normal vision and simulated protanopia,",
    "deuteranopia and tritanopia (Machado, Oliveira and Fernandes 2009, full severity). Above 10 is",
    `clearly distinct and 5 to 10 is distinct side by side; the test requires at least ${checks.distinct.min}.`,
    "Every status also carries an icon and a word, and chart series carry direct labels, so colour",
    "is never the only cue.",
    "",
    "| Theme | Pair | Normal | Protanopia | Deuteranopia | Tritanopia |",
    "| --- | --- | ---: | ---: | ---: | ---: |",
    ...apart,
    "",
  ].join("\n");
}
